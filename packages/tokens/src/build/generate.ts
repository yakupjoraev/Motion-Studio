import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

import { toCss } from './to-css'
import { toTailwind } from './to-tailwind'

/**
 * `pnpm generate:tokens`. Writes the one generated stylesheet: the `@theme` block that binds Tailwind's
 * namespaces to the runtime variables, then the variable values themselves for both modes and all four
 * elevation styles.
 *
 * Generation is deterministic — no timestamp, no environment, no map iteration whose order could shift.
 * `generate.test.ts` asserts the committed file matches a fresh run, so a token edit without a
 * regeneration fails CI rather than drifting quietly.
 *
 * The output is in Biome's ignore list for the same reason: the formatter strips trailing zeros from
 * `oklch(19.5% 0.010 265)`, swaps the quotes inside `url()` and reflows long declarations, all of which
 * put the committed sheet out of step with the generator that has to reproduce it.
 */

const HEADER = '/* Generated by packages/tokens. Do not edit. */'

/**
 * One sheet per app that renders the design system, resolved from this module so the script produces
 * the same paths from any working directory.
 *
 * The bytes are identical; the copies exist because each app's CSS entry imports its own, and a
 * cross-app import would break `ARCHITECTURE.md` § Dependency graph — nothing depends on `apps/*`.
 */
const APPS = ['web', 'storybook'] as const

export const OUTPUT_PATHS: readonly string[] = APPS.map((app) =>
  resolve(dirname(fileURLToPath(import.meta.url)), `../../../../apps/${app}/src/styles/theme.css`),
)

export function generateThemeCss(): string {
  return `${[HEADER, toTailwind(), toCss()].join('\n\n')}\n`
}

export async function writeThemeCss(paths: readonly string[] = OUTPUT_PATHS): Promise<void> {
  const css = generateThemeCss()

  for (const path of paths) {
    await mkdir(dirname(path), { recursive: true })
    await writeFile(path, css, 'utf8')
  }
}

/**
 * Writes only when run as the script. Without the guard, `generate.test.ts` importing this module to
 * compare the committed bytes would rewrite the very file it is checking, and the check would pass by
 * construction.
 */
const invokedDirectly = import.meta.url === pathToFileURL(process.argv[1] ?? '').href

if (invokedDirectly) {
  await writeThemeCss()
}
