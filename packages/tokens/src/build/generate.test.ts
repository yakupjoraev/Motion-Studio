import { readFile } from 'node:fs/promises'
import { describe, expect, it } from 'vitest'

import { OUTPUT_PATH, generateThemeCss } from './generate'
import { toCss } from './to-css'
import { toTailwind } from './to-tailwind'

/**
 * The three properties the generated sheet has to hold, and the reason each one is a test rather than a
 * convention:
 *
 * 1. **The committed file matches a fresh run.** A token edit without a regeneration would otherwise
 *    ship a stylesheet that disagrees with the source of truth, and nothing would notice.
 * 2. **Two runs produce identical bytes.** Non-determinism turns every regeneration into a diff and
 *    trains reviewers to skim past it.
 * 3. **Every variable the `@theme` block references is declared.** This is the indirection's failure
 *    mode: a mapping to a variable nobody writes yields a utility that silently resolves to nothing.
 */

const declaredNames = (css: string): Set<string> =>
  new Set(
    css.match(/^\s+(--ms-[A-Za-z0-9-]+):/gm)?.map((line) => line.trim().replace(':', '')) ?? [],
  )

const referencedNames = (theme: string): string[] => [
  ...new Set(theme.match(/var\((--ms-[A-Za-z0-9-]+)\)/g)?.map((call) => call.slice(4, -1)) ?? []),
]

describe('generateThemeCss', () => {
  it('is deterministic', () => {
    expect(generateThemeCss()).toBe(generateThemeCss())
  })

  it('matches the committed apps/web/src/styles/theme.css byte for byte', async () => {
    const committed = await readFile(OUTPUT_PATH, 'utf8')

    expect(committed).toBe(generateThemeCss())
  })

  it('marks the file as generated on its first line', () => {
    expect(generateThemeCss().split('\n')[0]).toBe(
      '/* Generated by packages/tokens. Do not edit. */',
    )
  })

  it('ends with a single newline', () => {
    expect(generateThemeCss().endsWith('}\n')).toBe(true)
  })

  it('uses LF throughout, which is what the formatter requires', () => {
    expect(generateThemeCss()).not.toContain('\r')
  })
})

describe('the variable indirection', () => {
  it('declares every --ms-* variable the @theme block points at', () => {
    const declared = declaredNames(toCss())
    const missing = referencedNames(toTailwind()).filter((name) => !declared.has(name))

    expect(missing).toEqual([])
  })

  it('never inlines a value into the @theme block', () => {
    // Every mapping must be a `var(--ms-…)` reference. A literal here would be a theme change that
    // needs a rebuild instead of a variable write.
    //
    // The alphabet allows a capital, because `foreground-onAccent` is the token's name in
    // `DESIGN_SYSTEM.md` § Semantic tokens and it stays that name all the way through: TypeScript key,
    // CSS variable, utility class. Verified against a real build — Tailwind emits
    // `.text-foreground-onAccent { color: var(--color-foreground-onAccent) }` and it resolves.
    for (const line of toTailwind().split('\n').slice(1, -1)) {
      expect(line).toMatch(/^ {2}--[A-Za-z0-9-]+: var\(--ms-[A-Za-z0-9-]+\);$/)
    }
  })

  it('declares the dark mode block on an attribute, so switching modes is one attribute write', () => {
    expect(toCss()).toContain(":root[data-color-mode='dark'] {")
  })

  it('names both attributes on every non-default elevation block, so order cannot decide', () => {
    for (const style of ['flat', 'sharp', 'glow'] as const) {
      expect(toCss()).toContain(`:root[data-elevation='${style}'] {`)
      expect(toCss()).toContain(`:root[data-color-mode='dark'][data-elevation='${style}'] {`)
    }
  })

  it('keeps the reduced-motion factor separate from the theme scale', () => {
    // ADR-021: the theme writes `--ms-motion-scale` inline, which outranks the media query. If the
    // query ever targets that same variable again, reduced motion stops working on themed documents.
    const css = toCss()

    expect(css).toContain('--ms-motion-scale: 1;')
    expect(css).toContain('--ms-reduced-motion: 1;')
    expect(css).toContain('--ms-reduced-motion: 0;')
    expect(css).not.toContain('--ms-motion-scale: 0;')
  })

  it('multiplies every duration by both motion factors', () => {
    for (const line of toCss()
      .split('\n')
      .filter((row) => row.includes('--ms-duration-'))) {
      expect(line).toMatch(
        /calc\(\d+ms \* var\(--ms-motion-scale\) \* var\(--ms-reduced-motion\)\);$/,
      )
    }
  })
})
